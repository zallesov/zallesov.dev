export const LED_FONTS = { "3x5": FONT_3X5, "5x7": FONT_5X7 } as const;
export type LedFontId = keyof typeof LED_FONTS;

/** Width of a line of text in font pixels. */
export function textWidth(text: string, font: LedFont = FONT_5X7): number {
  let w = 0;
  [...text.toUpperCase()].forEach((ch, i) => {
    if (i > 0) w += font.tracking;
    w += ch === " " ? font.space : font.w;
  });
  return w;
}

/** Calls `on(x, y)` for every lit font pixel of `text`, origin at the top-left. */
export function forEachPixel(text: string, on: (x: number, y: number) => void, font: LedFont = FONT_5X7) {
  let x = 0;
  [...text.toUpperCase()].forEach((ch, i) => {
    if (i > 0) x += font.tracking;
    if (ch === " ") {
      x += font.space;
      return;
    }
    const g = font.glyphs[ch];
    if (g) g.forEach((row, y) => row.forEach((lit, gx) => lit && on(x + gx, y)));
    x += font.w;
  });
}
