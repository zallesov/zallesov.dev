// Bitmap fonts for the LED matrix. Each glyph is rows of cells, "#" = lamp on.
// Uppercase only; unknown characters render as blanks.

export interface LedFont {
  w: number;
  h: number;
  /** Width of a space, in font pixels. */
  space: number;
  /** Empty columns between glyphs. */
  tracking: number;
  /** Empty rows between lines. */
  leading: number;
  glyphs: Record<string, boolean[][]>;
}

function build(raw: Record<string, string>, rest: Omit<LedFont, "glyphs">): LedFont {
  const glyphs = Object.fromEntries(
    Object.entries(raw).map(([ch, rows]) => [ch, rows.split(" ").map((r) => [...r].map((c) => c === "#"))]),
  );
  return { ...rest, glyphs };
}

